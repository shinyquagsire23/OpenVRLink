# Compiles quad.vert and quad.frag (standard and chroma-keyed variants) to SPIR-V and writes the bytecode into
# ../QuadShaders.swift.
# Checking in QuadShaders.swift avoids requiring glslc during normal Swift builds; re-run this script
# after modifying either shader.
#
# Uses glslc from PATH, or falls back to the newest Android NDK under $ANDROID_HOME.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
glslc=$(command -v glslc || true)
if [ -z "$glslc" ]; then
    sdk=${ANDROID_HOME:-$HOME/Library/Android/sdk}
    glslc=$(ls -d "$sdk"/ndk/*/shader-tools/*/glslc 2>/dev/null | sort | tail -1)
fi
[ -n "$glslc" ] || { echo "glslc not found" >&2; exit 1; }

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
"$glslc" -O "$here/quad.vert" -o "$work/vertex.spv"
"$glslc" -O "$here/quad.frag" -o "$work/fragment.spv"
"$glslc" -O -DKEYED "$here/quad.frag" -o "$work/keyed.spv"

words() {
    od -An -v -t x4 "$1" | tr -s ' \n' '\n' | sed '/^$/d' | awk '
        { line = line (line == "" ? "        " : ", ") "0x" $1 }
        NR % 8 == 0 { print line ","; line = "" }
        END { if (line != "") print line "," }'
}
{
    cat <<'HEADER'
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.

// Generated by Shaders/compile.sh from Shaders/quad.vert and Shaders/quad.frag. Do not edit.

/// Compiled SPIR-V bytecode for the Vulkan quad vertex and fragment shaders.
enum QuadShaders {
    static let vertex: [UInt32] = [
HEADER
    words "$work/vertex.spv"
    printf '    ]\n\n    static let fragment: [UInt32] = [\n'
    words "$work/fragment.spv"
    printf '    ]\n\n    /// Chroma-keyed fragment shader variant using dual-source blending.\n'
    printf '    static let keyedFragment: [UInt32] = [\n'
    words "$work/keyed.spv"
    printf '    ]\n}\n'
} > "$here/../QuadShaders.swift"
echo "wrote $here/../QuadShaders.swift"
